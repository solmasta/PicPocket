// Shared Jest setup goes here when frontend tests need it.

// jsdom doesn't implement matchMedia; ThemeContext relies on it to read the
// system color-scheme preference.
if (typeof window !== 'undefined' && !window.matchMedia) {
  window.matchMedia = (query) => ({
    matches: false,
    media: query,
    onchange: null,
    addListener: () => {},
    removeListener: () => {},
    addEventListener: () => {},
    removeEventListener: () => {},
    dispatchEvent: () => false,
  });
}
